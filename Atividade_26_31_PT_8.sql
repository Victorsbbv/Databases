# Relatório de vendas por cliente
SELECT c.nome AS cliente, SUM(p.valor_total) AS total_vendas
FROM Pedidos p
JOIN Clientes c ON p.cliente_id = c.id
GROUP BY c.nome
ORDER BY total_vendas DESC;

# Consultar pedidos de um cliente específico
SELECT p.*, pr.nome AS produto
FROM Pedidos p
JOIN Produtos pr ON p.pedido_id = pr.id
WHERE p.cliente_id = 3;

# Relatório de total de vendas
